def get_db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    conn = get_db()
    c = conn.cursor()
    # Drop old table if exists
    c.execute('DROP TABLE IF EXISTS posts')
    # Create new table with image_url and video_url columns
    c.execute('''CREATE TABLE posts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        post_id INTEGER UNIQUE,
        title TEXT NOT NULL,
        category TEXT,
        category_slug TEXT,
        date TEXT,
        excerpt TEXT,
        content TEXT,
        content_html TEXT,
        author TEXT DEFAULT '许文锋',
        image_url TEXT,
        video_url TEXT
    )''')
    conn.commit()
    conn.close()

